export function findScreen(id: string | null | undefined) {
  return approvalScreens.find(screen => screen.id === id);
}

export function buildScreenRequest(screen: ApprovalScreen): ApprovalRequest {
  return findVariant(findJourney(screen.journey), screen.variant).buildRequest(screen.signerKind);
}
